import { describe, expect, it } from "vitest";
import { SqliteDriver } from "../src/impl/store/sqlite/sqlite-driver.js";
import { sqliteSnapshot } from "../src/state/snapshot.js";

// The schema snapshot is split by owner prefix (docs/design/10-event-driven.md): one text per prefix that has
// tables, named after the prefix, plus `unprefixed` for the rest; each index goes with its table.

describe("sqliteSnapshot", () => {
  it("groups every table and its indexes by owner prefix", async () => {
    const db = new SqliteDriver(":memory:");
    for (const sql of [
      "CREATE TABLE bus_b (id INTEGER)",
      "CREATE TABLE bus_a (id INTEGER)",
      "CREATE INDEX zz_on_bus_a ON bus_a (id)",
      "CREATE TABLE worker_runs (id INTEGER)",
      "CREATE TABLE schema_migrations (id INTEGER)",
    ]) await db.run(sql);
    const files = await sqliteSnapshot(db, ["bus_", "worker_", "ui_"]);
    await db.close();

    expect([...files.keys()].sort()).toEqual(["bus.sql", "unprefixed.sql", "worker.sql"]);
    const bus = files.get("bus.sql")!;
    expect(bus.startsWith("-- Generated by `npm run schema:snapshot`")).toBe(true);
    const order = ["CREATE TABLE bus_a", "CREATE TABLE bus_b", "CREATE INDEX zz_on_bus_a"].map((s) => bus.indexOf(s));
    expect(order.every((i) => i >= 0)).toBe(true);
    expect(order).toEqual([...order].sort((a, b) => a - b));
    expect(bus).not.toContain("worker_runs");
    expect(files.get("worker.sql")).toContain("CREATE TABLE worker_runs");
    expect(files.get("unprefixed.sql")).toContain("CREATE TABLE schema_migrations");
  });
});
