// The generated schema (schema/sqlite/controller.sql, `npm run schema:snapshot`) holds both skill improvement tables
// (design 07-self-improvement) with the columns, state check and keys the migration creates.
// tests/architecture/schema-snapshot.test.ts checks the whole file is fresh; this names what the new tables must say.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const SQL = readFileSync(join(import.meta.dirname, "..", "schema", "sqlite", "controller.sql"), "utf8");

/** The body of `CREATE TABLE <name> (...)` in the snapshot, or null when the table is not there. */
function table(name: string): string | null {
  const m = new RegExp(`CREATE TABLE ${name} \\(([\\s\\S]*?)\\n\\s*\\);`).exec(SQL);
  return m ? m[1]! : null;
}

describe("schema/sqlite/controller.sql: skill improvement tables", () => {
  it("is the generated snapshot", () => {
    expect(SQL.startsWith("-- Generated by `npm run schema:snapshot`")).toBe(true);
  });

  it("has controller_skill_drafts with its columns and only the five states", () => {
    const body = table("controller_skill_drafts");
    expect(body).not.toBeNull();
    for (const c of ["id", "project_key", "skill_ref", "state", "tokens", "detail", "created_at", "updated_at"]) expect(body).toMatch(new RegExp(`^\\s*${c}\\s`, "m"));
    expect(body).toMatch(/id\s+TEXT PRIMARY KEY/);
    expect(body).toContain("CHECK (state IN ('tried', 'proposed', 'promoted', 'rejected', 'held'))");
  });

  it("has controller_skill_draft_days keyed by project and day", () => {
    const body = table("controller_skill_draft_days");
    expect(body).not.toBeNull();
    for (const c of ["project_key", "day", "count"]) expect(body).toMatch(new RegExp(`^\\s*${c}\\s`, "m"));
    expect(body).toContain("PRIMARY KEY (project_key, day)");
  });
});
