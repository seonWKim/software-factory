// Generates web/src/i18n/en.ts, the English catalog barrel, from the area files in web/src/i18n/en/.
// A local development script (design 09-dashboard-shell): `npm run i18n:catalog` writes the file, so adding an
// area file never needs a hand edit to a shared import or spread line. tests/web-i18n-keys.test.ts fails when the
// checked-in barrel differs from render().
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const CATALOG_DIR = join(import.meta.dirname, "..", "web", "src", "i18n");
export const BARREL = join(CATALOG_DIR, "en.ts");
const AREA_DIR = join(CATALOG_DIR, "en");
const EXPORT = /^export const ([A-Za-z_$][\w$]*) = \{/m;

/** One area file: its base name (no `.ts`) and the name of the object it exports. */
export interface Area {
  file: string;
  name: string;
}

/** The area files in web/src/i18n/en/, sorted by file name, each with its exported object's name. */
export function readAreas(dir: string = AREA_DIR): Area[] {
  return readdirSync(dir)
    .filter((n) => n.endsWith(".ts"))
    .sort()
    .map((n) => {
      const name = EXPORT.exec(readFileSync(join(dir, n), "utf8"))?.[1];
      if (name === undefined) throw new Error(`web/src/i18n/en/${n} exports no "export const <name> = {"`);
      return { file: n.slice(0, -".ts".length), name };
    });
}

/** The barrel text: one import and one spread per area, then the MessageKey type. */
export function render(areas: readonly Area[]): string {
  return [
    "// GENERATED by scripts/i18n-catalog.ts from the area files in en/. Do not edit this file: add or edit an area",
    "// file and run `npm run i18n:catalog`. A key's prefix (the part before its first dot) decides its area file",
    "// (tests/web-i18n-keys.test.ts). `{name}` in a text marks a value the caller fills in.",
    ...areas.map((a) => `import { ${a.name} } from "./en/${a.file}.js";`),
    "",
    "export const en = {",
    ...areas.map((a) => `  ...${a.name},`),
    "} as const;",
    "",
    "export type MessageKey = keyof typeof en;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(BARREL, render(readAreas()));
}
