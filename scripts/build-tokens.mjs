// Generates web/src/tokens.css from design-system/tokens.json (the one token source).
// `node scripts/build-tokens.mjs` writes the file; `--stdout` prints it instead.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(join(root, "design-system", "tokens.json"), "utf8"));

const decls = (entries) => entries.map(([k, v]) => `  --${k}: ${v};`);
const colors = (mode) => decls(Object.entries(tokens.colors[mode]));
const pills = (mode) =>
  decls(
    Object.entries(tokens.pills[mode]).flatMap(([status, parts]) =>
      Object.entries(parts).map(([part, v]) => [`pill-${status}-${part}`, v]),
    ),
  );
const scale = (prefix, map) => decls(Object.entries(map).map(([k, v]) => [`${prefix}-${k}`, v]));

const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}\n`;

export function render() {
  return [
    "/* GENERATED by scripts/build-tokens.mjs from design-system/tokens.json. Do not edit this file: edit the JSON and run `npm run build:tokens`. */\n",
    block(":root", [
      ...colors("light"),
      ...pills("light"),
      ...scale("fs", tokens.type),
      ...scale("sp", tokens.space),
      ...scale("r", tokens.radius),
    ]),
    block(".dark", [...colors("dark"), ...pills("dark")]),
  ].join("\n");
}

if (process.argv.includes("--stdout")) process.stdout.write(render());
else writeFileSync(join(root, "web", "src", "tokens.css"), render());
